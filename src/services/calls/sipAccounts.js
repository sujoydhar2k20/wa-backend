'use strict';

/**
 * Per-user calling accounts on Asterisk.
 *
 * Every active superadmin/admin/staff user gets:
 *   u<userId>        WebRTC account (web panel / Android app, over wss via nginx)
 *   u<userId>-desk   optional TLS + SDES account for Linphone / desk phones (user.sip.deskPhone)
 * Passwords are random, stored encrypted on the User, and written into a generated
 * Asterisk include file (mode 600, owned by the container's asterisk uid). After a change
 * the backend asks Asterisk (AMI, localhost only) to reload.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const User = require('../../models/User');
const { logger } = require('../../utils/logger');
const { seal, open } = require('./secretBox');
const { amiCommand } = require('./ami');
const callingConfig = require('./config');

const CALL_ROLES = ['superadmin', 'admin', 'staff'];
const endpointFor = (userId) => `u${String(userId)}`;
const deskEndpointFor = (userId) => `u${String(userId)}-desk`;
const userIdFromEndpoint = (ep) => {
  const m = /^u([0-9a-f]{24})(-desk)?$/.exec(String(ep || ''));
  return m ? { userId: m[1], device: m[2] ? 'desk' : 'app' } : null;
};
const newPassword = () => crypto.randomBytes(24).toString('base64url'); // [A-Za-z0-9_-] only: safe in Asterisk config

async function ensureAccounts() {
  const users = await User.find({ isActive: true, role: { $in: CALL_ROLES } })
    .select('+sip.passwordEnc').lean();
  for (const u of users) {
    if (!u.sip?.passwordEnc) {
      const passwordEnc = seal(newPassword());
      await User.updateOne({ _id: u._id }, { $set: { 'sip.passwordEnc': passwordEnc, 'sip.createdAt': new Date() } });
      u.sip = { ...(u.sip || {}), passwordEnc };
    }
  }
  return users;
}

const clean = (s) => String(s || '').replace(/[^\p{L}\p{N} ._-]/gu, '').slice(0, 40) || 'Staff';

function renderPjsip(users) {
  const out = [
    '; GENERATED by the backend (services/calls/sipAccounts.js). Do not edit: changes are overwritten.',
    '',
  ];
  for (const u of users) {
    const ep = endpointFor(u._id);
    const pw = open(u.sip.passwordEnc);
    const cid = `"${clean(u.name)}" <${ep}>`;
    out.push(
      `[${ep}](webrtc_user)`, `auth=${ep}`, `aors=${ep}`, `callerid=${cid}`,
      `[${ep}](user_auth)`, `username=${ep}`, `password=${pw}`,
      `[${ep}](user_aor)`, 'max_contacts=10', '',
    );
    if (u.sip?.deskPhone) {
      const dep = deskEndpointFor(u._id);
      out.push(
        `[${dep}](desk_user)`, `auth=${dep}`, `aors=${dep}`, `callerid=${cid}`,
        `[${dep}](user_auth)`, `username=${dep}`, `password=${pw}`,
        `[${dep}](user_aor)`, '',
      );
    }
  }
  return `${out.join('\n')}\n`;
}

function renderDialplan(users) {
  const eps = [];
  for (const u of users) {
    eps.push(endpointFor(u._id));
    if (u.sip?.deskPhone) eps.push(deskEndpointFor(u._id));
  }
  return [
    '; GENERATED by the backend. Fallback ring list used only if the backend cannot be reached.',
    '[users-fallback]',
    `exten => s,1,Return(${eps.join('~')})`,
    '',
  ].join('\n');
}

function writeIfChanged(file, content, uid) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  const tmp = `${file}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, content, { mode: 0o600 });
  try { fs.chownSync(tmp, uid, uid); } catch (e) {
    // Backend not running as root: let the asterisk user read it via world-read instead (file holds passwords!)
    logger.warn(`[calls] cannot chown ${path.basename(file)} to uid ${uid} (${e.code}); making it 0644`);
    fs.chmodSync(tmp, 0o644);
  }
  fs.renameSync(tmp, file);
  return true;
}

let syncing = null;
let pending = false;
let reloadPending = { pjsip: false, dialplan: false }; // retried on the next sync if Asterisk was unreachable

async function syncNow() {
  const cfg = callingConfig.get();
  if (!cfg.enabled) return { skipped: true };
  if (syncing) { pending = true; return syncing; }
  syncing = (async () => {
    try {
      const users = await ensureAccounts();
      fs.mkdirSync(cfg.generatedDir, { recursive: true, mode: 0o750 });
      const a = writeIfChanged(path.join(cfg.generatedDir, 'pjsip_users.conf'), renderPjsip(users), cfg.asteriskUid);
      const b = writeIfChanged(path.join(cfg.generatedDir, 'extensions_users.conf'), renderDialplan(users), cfg.asteriskUid);
      if (a) reloadPending.pjsip = true;
      if (b) reloadPending.dialplan = true;
      if (reloadPending.pjsip || reloadPending.dialplan) {
        try {
          if (reloadPending.pjsip) { await amiCommand(cfg.ami, 'module reload res_pjsip.so'); reloadPending.pjsip = false; }
          if (reloadPending.dialplan) { await amiCommand(cfg.ami, 'dialplan reload'); reloadPending.dialplan = false; }
          logger.info(`[calls] calling accounts updated (${users.length} users), Asterisk reloaded`);
        } catch (e) {
          logger.error(`[calls] accounts written but Asterisk reload failed (will retry): ${e.message}`);
        }
      }
      return { users: users.length, changed: a || b };
    } finally {
      syncing = null;
      if (pending) { pending = false; setTimeout(() => syncNow().catch(() => {}), 500); }
    }
  })();
  return syncing;
}

let timer;
function scheduleSync() {
  clearTimeout(timer);
  timer = setTimeout(() => syncNow().catch((e) => logger.error(`[calls] account sync failed: ${e.message}`)), 1500);
}

function startPeriodicSync(intervalMs = 120000) {
  if (!callingConfig.get().enabled) return null;
  scheduleSync();
  const t = setInterval(() => syncNow().catch((e) => logger.error(`[calls] account sync failed: ${e.message}`)), intervalMs);
  t.unref?.();
  return t;
}

async function getCredentials(userId) {
  const u = await User.findById(userId).select('+sip.passwordEnc').lean();
  if (!u || !u.isActive || !CALL_ROLES.includes(u.role)) return null;
  if (!u.sip?.passwordEnc) {
    if (!callingConfig.get().enabled) return null;
    await syncNow();
    const again = await User.findById(userId).select('+sip.passwordEnc').lean();
    if (!again?.sip?.passwordEnc) return null;
    u.sip = again.sip;
  }
  return { username: endpointFor(u._id), password: open(u.sip.passwordEnc), displayName: u.name, deskPhone: !!u.sip.deskPhone };
}

async function resetPassword(userId) {
  await User.updateOne({ _id: userId }, { $set: { 'sip.passwordEnc': seal(newPassword()), 'sip.createdAt': new Date() } });
  await syncNow();
}

module.exports = {
  CALL_ROLES, endpointFor, deskEndpointFor, userIdFromEndpoint,
  renderPjsip, renderDialplan, ensureAccounts, syncNow, scheduleSync, startPeriodicSync, getCredentials, resetPassword,
};
